using System.Runtime.InteropServices;

namespace Tremors;

/// <summary>
/// Global low-level mouse hook (WH_MOUSE_LL). Every physical mouse event passes
/// through <see cref="Filter"/> before any window sees it. The filter returns
/// <c>true</c> to let the event through or <c>false</c> to swallow it.
/// </summary>
/// <remarks>
/// The hook callback runs on the thread that installed it, so that thread must
/// pump messages (the WinForms UI thread does). Keep the callback fast: Windows
/// silently removes low-level hooks that exceed the system timeout.
/// </remarks>
internal sealed class Mouse : IDisposable
{
    public const int WM_MOUSEMOVE = 0x0200;
    public const int WM_LBUTTONDOWN = 0x0201;
    public const int WM_RBUTTONDOWN = 0x0204;
    public const int WM_MBUTTONDOWN = 0x0207;
    public const int WM_MOUSEWHEEL = 0x020A;
    public const int WM_XBUTTONDOWN = 0x020B;
    public const int WM_MOUSEHWHEEL = 0x020E;

    /// <summary>Set when the event was generated by software (SendInput and the like).</summary>
    public const uint LLMHF_INJECTED = 0x01;

    private const int WH_MOUSE_LL = 14;

    [StructLayout(LayoutKind.Sequential)]
    public struct POINT
    {
        public int X;
        public int Y;
    }

    [StructLayout(LayoutKind.Sequential)]
    public struct MSLLHOOKSTRUCT
    {
        public POINT pt;
        public uint mouseData;
        public uint flags;
        public uint time;
        public IntPtr dwExtraInfo;
    }

    /// <summary>Called for every mouse event with the window message and its data.</summary>
    public Func<int, MSLLHOOKSTRUCT, bool>? Filter { get; set; }

    public bool Installed => _hook != IntPtr.Zero;

    private delegate IntPtr HookProc(int nCode, IntPtr wParam, IntPtr lParam);

    private readonly HookProc _proc; // field keeps the delegate alive for native code
    private IntPtr _hook;

    public Mouse() => _proc = Callback;

    public void Install()
    {
        if (Installed) return;
        _hook = SetWindowsHookEx(WH_MOUSE_LL, _proc, GetModuleHandle(null), 0);
        if (_hook == IntPtr.Zero)
            throw new System.ComponentModel.Win32Exception(Marshal.GetLastWin32Error());
    }

    public void Uninstall()
    {
        if (!Installed) return;
        UnhookWindowsHookEx(_hook);
        _hook = IntPtr.Zero;
    }

    public void Dispose() => Uninstall();

    /// <summary>Current cursor position in physical screen pixels.</summary>
    public static POINT CursorPosition()
    {
        GetCursorPos(out var p);
        return p;
    }

    /// <summary>Moves the cursor and returns where Windows actually put it (it clamps to the screens).</summary>
    public static POINT MoveCursor(int x, int y)
    {
        SetCursorPos(x, y);
        return CursorPosition();
    }

    private IntPtr Callback(int nCode, IntPtr wParam, IntPtr lParam)
    {
        if (nCode >= 0 && Filter is { } filter)
        {
            bool pass = true;
            try
            {
                var data = Marshal.PtrToStructure<MSLLHOOKSTRUCT>(lParam);
                pass = filter((int)wParam, data);
            }
            catch
            {
                // Never let an exception escape into native code; fail open.
            }
            if (!pass) return 1;
        }
        return CallNextHookEx(_hook, nCode, wParam, lParam);
    }

    [DllImport("user32.dll", SetLastError = true)]
    private static extern IntPtr SetWindowsHookEx(int idHook, HookProc lpfn, IntPtr hMod, uint dwThreadId);

    [DllImport("user32.dll")]
    [return: MarshalAs(UnmanagedType.Bool)]
    private static extern bool UnhookWindowsHookEx(IntPtr hhk);

    [DllImport("user32.dll")]
    private static extern IntPtr CallNextHookEx(IntPtr hhk, int nCode, IntPtr wParam, IntPtr lParam);

    [DllImport("kernel32.dll", CharSet = CharSet.Unicode)]
    private static extern IntPtr GetModuleHandle(string? lpModuleName);

    [DllImport("user32.dll")]
    [return: MarshalAs(UnmanagedType.Bool)]
    private static extern bool GetCursorPos(out POINT lpPoint);

    [DllImport("user32.dll")]
    [return: MarshalAs(UnmanagedType.Bool)]
    private static extern bool SetCursorPos(int x, int y);
}
